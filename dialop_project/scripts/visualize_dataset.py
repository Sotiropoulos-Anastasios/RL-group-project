#!/usr/bin/env python3
"""Create a dependency-free Markdown overview of the processed data."""

from __future__ import annotations

import argparse
import json
from collections import Counter
from pathlib import Path
from statistics import mean
from typing import Any


PROJECT_DIR = Path(__file__).resolve().parents[1]


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Write simple Markdown graphs for processed DialOp data."
    )
    parser.add_argument(
        "--processed-dir",
        type=Path,
        default=PROJECT_DIR / "data" / "processed",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=PROJECT_DIR / "reports" / "visualizations" / "data_overview.md",
    )
    return parser.parse_args()


def read_jsonl(path: Path) -> list[dict[str, Any]]:
    with path.open("r", encoding="utf-8") as handle:
        return [json.loads(line) for line in handle if line.strip()]


def bar(value: float, maximum: float, width: int = 40) -> str:
    filled = round((value / maximum) * width) if maximum else 0
    return "#" * filled + " " * (width - filled)


def main() -> None:
    args = parse_args()
    episodes = read_jsonl(args.processed_dir / "episodes.jsonl")
    actions = read_jsonl(args.processed_dir / "actions.jsonl")
    action_counts = Counter(action["kind"] for action in actions)
    split_counts = Counter(episode["split"] for episode in episodes)
    scores = [episode["human_outcome"]["score"] for episode in episodes]
    best_scores = [episode["best_assignment_reward"] for episode in episodes]
    normalized = [
        episode["human_outcome"]["normalized_score"] for episode in episodes
    ]
    max_actions = max(action_counts.values())
    lines = [
        "# DialOp Processed Data Overview",
        "",
        "This report is generated by `scripts/visualize_dataset.py`.",
        "",
        "## Dataset counts",
        "",
        "| Quantity | Value |",
        "|---|---:|",
        f"| Episodes | {len(episodes)} |",
        f"| Actions | {len(actions)} |",
        f"| Messages | {action_counts['message']} |",
        f"| Proposals | {action_counts['proposal']} |",
        f"| Proposal responses | {action_counts['proposal_response']} |",
        "",
        "## Episode splits",
        "",
        "| Split | Episodes |",
        "|---|---:|",
        f"| Train | {split_counts['train']} |",
        f"| Validation | {split_counts['validation']} |",
        f"| Test | {split_counts['test']} |",
        "",
        "## Actions by type",
        "",
        "```text",
    ]
    for kind in ("message", "proposal", "proposal_response"):
        value = action_counts[kind]
        lines.append(f"{kind:<20} {value:>5} |{bar(value, max_actions)}|")
    lines.extend(
        [
            "```",
            "",
            "## Score comparison",
            "",
            "```text",
            f"Human final score     {mean(scores):8.2f} |{bar(mean(scores), max(best_scores))}|",
            f"Recorded best reward  {mean(best_scores):8.2f} |{bar(mean(best_scores), max(best_scores))}|",
            "```",
            "",
            "## Normalized score",
            "",
            "DialOp defines this as `proposal_reward / best_assignment_reward`.",
            "The private-view convention is `int(oracle_cell * player_scale)` for visible cells and `null` for hidden cells.",
            "",
            f"Mean: `{mean(normalized):.4f}`<br>",
            f"Minimum: `{min(normalized):.4f}`<br>",
            f"Maximum: `{max(normalized):.4f}`",
            "",
        ]
    )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")
    print(f"Wrote {args.output.resolve()}")


if __name__ == "__main__":
    main()
